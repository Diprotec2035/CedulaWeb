/* SP_SEL_REPORTE_ACCESO_DISPOSITIVO_LOG -> -----SP_SEL_REPORTE_ACCESO_DISPOSITIVO_LOG */
CREATE DEFINER = 'root'@'%' PROCEDURE `-----SP_SEL_REPORTE_ACCESO_DISPOSITIVO_LOG`(
        IN `P_EMP_RUT` VARCHAR(10),
        IN `P_BUSCADOR` VARCHAR(100),
        IN `P_DESDE` VARCHAR(10),
        IN `P_HASTA` VARCHAR(10),
        IN `P_CAMPO` TINYINT,
        IN `P_ORDEN` TINYINT
    )
    NOT DETERMINISTIC
    CONTAINS SQL
    SQL SECURITY DEFINER
    COMMENT ''
BEGIN
    SELECT AD.ADL_ID,
           DATE_FORMAT(AD.ADL_FECHA, '%d-%m-%Y') AS ADL_FECHA,
           DATE_FORMAT(AD.ADL_HORA, '%H:%i:%s') AS ADL_HORA,
           INET_NTOA(AD.ADL_IP) AS ADL_IP,
           AD.DIS_ID, AD.ADL_ENDPOINT, AD.ADL_STATUS_CODE,
           AD.ADL_CORRELATION_ID, AD.ADL_DURACION_MS,
           AD.ADL_METODO_HTTP, AD.ADL_USER_AGENT, AD.ADL_RESULTADO,
           AD.ADL_DEVICE_SESSION_TOKEN, AD.EMP_RUT,
           DIS.DIS_SERIALNUMBER, DIS.DIS_MARCA, DIS.DIS_MODELO
    FROM tbl_acceso_dispositivo_log AD
    LEFT JOIN tbl_dispositivo DIS ON DIS.DIS_ID = AD.DIS_ID
    WHERE AD.EMP_RUT = UPPER(TRIM(P_EMP_RUT))
      AND AD.ADL_FECHA >= STR_TO_DATE(P_DESDE, '%d-%m-%Y')
      AND AD.ADL_FECHA <= STR_TO_DATE(P_HASTA, '%d-%m-%Y')
      AND (P_BUSCADOR = '' OR INET_NTOA(AD.ADL_IP) LIKE CONCAT('%', P_BUSCADOR, '%'))
    ORDER BY
      CASE WHEN P_CAMPO = 1 AND P_ORDEN = 1 THEN AD.ADL_FECHA END ASC,
      CASE WHEN P_CAMPO = 1 AND P_ORDEN = 2 THEN AD.ADL_FECHA END DESC,
      CASE WHEN P_CAMPO = 2 AND P_ORDEN = 1 THEN AD.DIS_ID END ASC,
      CASE WHEN P_CAMPO = 2 AND P_ORDEN = 2 THEN AD.DIS_ID END DESC,
      CASE WHEN P_CAMPO = 3 AND P_ORDEN = 1 THEN AD.ADL_IP END ASC,
      CASE WHEN P_CAMPO = 3 AND P_ORDEN = 2 THEN AD.ADL_IP END DESC;
END$$

DROP PROCEDURE IF EXISTS `SP_SEL_REPORTE_ACCESO_DISPOSITIVO_LOG`$$

/* SP_SEL_REPORTE_ACCESO_WEB_LOG -> -----SP_SEL_REPORTE_ACCESO_WEB_LOG */
CREATE DEFINER = 'root'@'%' PROCEDURE `-----SP_SEL_REPORTE_ACCESO_WEB_LOG`(
        IN `P_EMP_RUT` VARCHAR(10),
        IN `P_BUSCADOR` VARCHAR(100),
        IN `P_DESDE` VARCHAR(10),
        IN `P_HASTA` VARCHAR(10),
        IN `P_CAMPO` TINYINT,
        IN `P_ORDEN` TINYINT
    )
    NOT DETERMINISTIC
    CONTAINS SQL
    SQL SECURITY DEFINER
    COMMENT ''
BEGIN
    SELECT AW.AWL_ID,
           DATE_FORMAT(AW.AWL_FECHA, '%d-%m-%Y') AS AWL_FECHA,
           DATE_FORMAT(AW.AWL_HORA, '%H:%i:%s') AS AWL_HORA,
           INET_NTOA(AW.AWL_IP) AS AWL_IP,
           AW.USU_RUT,
           CONCAT(US.USU_NOMBRE, ' ', US.USU_APELLIDO) AS USU_NOMBRE,
           AW.EMP_RUT
    FROM tbl_acceso_web_log AW
    INNER JOIN tbl_usuario US ON US.USU_RUT = AW.USU_RUT
    WHERE AW.EMP_RUT = UPPER(TRIM(P_EMP_RUT))
      AND AW.AWL_FECHA >= STR_TO_DATE(P_DESDE, '%d-%m-%Y')
      AND AW.AWL_FECHA <= STR_TO_DATE(P_HASTA, '%d-%m-%Y')
      AND (P_BUSCADOR = ''
           OR AW.USU_RUT LIKE CONCAT('%', P_BUSCADOR, '%')
           OR INET_NTOA(AW.AWL_IP) LIKE CONCAT('%', P_BUSCADOR, '%'))
    ORDER BY
      CASE WHEN P_CAMPO = 1 AND P_ORDEN = 1 THEN AW.AWL_FECHA END ASC,
      CASE WHEN P_CAMPO = 1 AND P_ORDEN = 2 THEN AW.AWL_FECHA END DESC,
      CASE WHEN P_CAMPO = 2 AND P_ORDEN = 1 THEN AW.USU_RUT END ASC,
      CASE WHEN P_CAMPO = 2 AND P_ORDEN = 2 THEN AW.USU_RUT END DESC,
      CASE WHEN P_CAMPO = 3 AND P_ORDEN = 1 THEN US.USU_NOMBRE END ASC,
      CASE WHEN P_CAMPO = 3 AND P_ORDEN = 2 THEN US.USU_NOMBRE END DESC,
      CASE WHEN P_CAMPO = 4 AND P_ORDEN = 1 THEN AW.AWL_IP END ASC,
      CASE WHEN P_CAMPO = 4 AND P_ORDEN = 2 THEN AW.AWL_IP END DESC;
