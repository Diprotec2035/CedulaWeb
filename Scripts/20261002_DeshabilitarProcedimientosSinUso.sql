CREATE DEFINER = 'root'@'%' PROCEDURE `-----SP_CEDULA_INS_REGLA`(
        IN `P_EMP_RUT` VARCHAR(10),
        IN `P_REG_NOMBRE` VARCHAR(100),
        IN `P_REG_NOMBRE_APELLIDO` TINYINT,
        IN `P_REG_EMPRESA` TINYINT,
        IN `P_REG_PATENTE` TINYINT,
        IN `P_REG_COMENTARIO` TINYINT,
        IN `P_REG_FOTOGRAFIA` TINYINT,
        IN `P_REG_ENTRADA_SALIDA` TINYINT,
        IN `P_REG_LISTA_BLANCA_NEGRA` TINYINT,
        IN `P_REG_ELIMINA_ENVIADOS` TINYINT,
        IN `P_REG_ESTADO` TINYINT,
        OUT `P_RETORNO` TINYINT UNSIGNED
    )
    NOT DETERMINISTIC
    CONTAINS SQL
    SQL SECURITY DEFINER
    COMMENT ''
BEGIN
    DECLARE V_REG_ID INT UNSIGNED;
    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        ROLLBACK;
        RESIGNAL;
    END;
    START TRANSACTION;
    INSERT INTO tbl_regla
    (
        EMP_RUT,
        REG_NOMBRE,
        REG_NOMBRE_APELLIDO,
        REG_EMPRESA,
        REG_PATENTE,
        REG_COMENTARIO,
        REG_FOTOGRAFIA,
        REG_ENTRADA_SALIDA,
        REG_LISTA_BLANCA_NEGRA,
        REG_ELIMINA_ENVIADOS,
        REG_ESTADO
    )
    VALUES
    (
        UPPER(TRIM(P_EMP_RUT)),
        UPPER(TRIM(P_REG_NOMBRE)),
        P_REG_NOMBRE_APELLIDO,
        P_REG_EMPRESA,
        P_REG_PATENTE,
        P_REG_COMENTARIO,
        P_REG_FOTOGRAFIA,
        P_REG_ENTRADA_SALIDA,
        P_REG_LISTA_BLANCA_NEGRA,
        P_REG_ELIMINA_ENVIADOS,
        P_REG_ESTADO
    );
    SET V_REG_ID = LAST_INSERT_ID();
    COMMIT;
    SET P_RETORNO = 0;
END$$

