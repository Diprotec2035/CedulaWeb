/* SP_SEL_REPORTE_MODULO_PERFIL -> -----SP_SEL_REPORTE_MODULO_PERFIL */
CREATE DEFINER = 'root'@'localhost' PROCEDURE `-----SP_SEL_REPORTE_MODULO_PERFIL`(
        IN `P_EMP_RUT` VARCHAR(10),
        IN `P_PER_ID` INTEGER UNSIGNED,
        IN `P_CAT_ID` INTEGER UNSIGNED,
        IN `P_CAMPO` TINYINT,
        IN `P_ORDEN` TINYINT
    )
    NOT DETERMINISTIC
    CONTAINS SQL
    SQL SECURITY DEFINER
    COMMENT ''
BEGIN
    SELECT IFNULL(MP.MP_ID, 0) AS MP_ID, P_PER_ID AS PER_ID,
           MO.MOD_ID, MO.MOD_NOMBRE,
           IFNULL(MP.MP_CONSULTA, 0) AS MP_CONSULTA,
           IFNULL(MP.MP_NUEVO, 0) AS MP_NUEVO,
           IFNULL(MP.MP_MODIFICA, 0) AS MP_MODIFICA,
           IFNULL(MP.MP_ESTADO, 1) AS MP_ESTADO,
           MP.MP_UPDATED_AT
    FROM tbl_modulo MO
    LEFT JOIN tbl_modulo_perfil MP
      ON MP.MOD_ID = MO.MOD_ID AND MP.PER_ID = P_PER_ID
    LEFT JOIN tbl_perfil PE
      ON PE.PER_ID = MP.PER_ID AND PE.EMP_RUT = UPPER(TRIM(P_EMP_RUT))
    WHERE MO.CAT_ID = P_CAT_ID AND MO.MOD_ADMINISTRADOR = 0
    ORDER BY
      CASE WHEN P_CAMPO = 1 AND P_ORDEN = 1 THEN MO.MOD_ID END ASC,
      CASE WHEN P_CAMPO = 1 AND P_ORDEN = 2 THEN MO.MOD_ID END DESC,
      CASE WHEN P_CAMPO = 2 AND P_ORDEN = 1 THEN MO.MOD_NOMBRE END ASC,
      CASE WHEN P_CAMPO = 2 AND P_ORDEN = 2 THEN MO.MOD_NOMBRE END DESC;
END$$

DROP PROCEDURE IF EXISTS `SP_SEL_REPORTE_MODULO_PERFIL`$$

