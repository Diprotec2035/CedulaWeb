CREATE DEFINER = 'UsuarioOwner'@'%' PROCEDURE `SP_SEL_REPORTE_EMPRESA_VISITA`(
        IN `P_EMP_RUT` VARCHAR(10),
        IN `P_BUSCADOR` VARCHAR(100),
        IN `P_EV_VIGENTE` TINYINT UNSIGNED,
        IN `P_CAMPO` TINYINT,
        IN `P_ORDEN` TINYINT
    )
    NOT DETERMINISTIC
    CONTAINS SQL
    SQL SECURITY DEFINER
    COMMENT ''
BEGIN
    SELECT
        EV.EMP_RUT,
        EV.EV_RUT,
        EV.EV_NOMBRE,
        EV.EV_EMPRESA,
        DATE_FORMAT(EV.EV_FECHA, '%d-%m-%Y') AS EV_FECHA,
        DATE_FORMAT(EV.EV_HORA, '%H:%i:%s') AS EV_HORA,
        EV.EV_VIGENTE
    FROM tbl_empresa_visita EV
    WHERE
        EV.EMP_RUT = UPPER(TRIM(P_EMP_RUT))
        AND (P_EV_VIGENTE IS NULL OR EV.EV_VIGENTE = P_EV_VIGENTE)
        AND (
            P_BUSCADOR = ''
            OR EV.EV_RUT LIKE CONCAT('%', P_BUSCADOR, '%')
            OR EV.EV_NOMBRE LIKE CONCAT('%', P_BUSCADOR, '%')
            OR EV.EV_EMPRESA LIKE CONCAT('%', P_BUSCADOR, '%')
        )
    ORDER BY
        CASE WHEN P_CAMPO = 1 AND P_ORDEN = 1 THEN EV.EV_RUT END ASC,
        CASE WHEN P_CAMPO = 1 AND P_ORDEN = 2 THEN EV.EV_RUT END DESC,
        CASE WHEN P_CAMPO = 2 AND P_ORDEN = 1 THEN EV.EV_NOMBRE END ASC,
        CASE WHEN P_CAMPO = 2 AND P_ORDEN = 2 THEN EV.EV_NOMBRE END DESC,
        CASE WHEN P_CAMPO = 3 AND P_ORDEN = 1 THEN EV.EV_EMPRESA END ASC,
        CASE WHEN P_CAMPO = 3 AND P_ORDEN = 2 THEN EV.EV_EMPRESA END DESC;
END$$

