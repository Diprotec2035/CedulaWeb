CREATE DEFINER = 'UsuarioOwner'@'%' PROCEDURE `SP_SEL_REPORTE_REGLAS`(
        IN `P_EMP_RUT` VARCHAR(10),
        IN `P_BUSCADOR` VARCHAR(100),
        IN `P_REG_ESTADO` TINYINT UNSIGNED,
        IN `P_CAMPO` TINYINT,
        IN `P_ORDEN` TINYINT
    )
    NOT DETERMINISTIC
    CONTAINS SQL
    SQL SECURITY DEFINER
    COMMENT ''
BEGIN
    SELECT
        R.REG_ID,
        R.REG_NOMBRE,
        R.REG_NOMBRE_APELLIDO,
        R.REG_EMPRESA,
        R.REG_PATENTE,
        R.REG_COMENTARIO,
        R.REG_FOTOGRAFIA,
        R.REG_ENTRADA_SALIDA,
        R.REG_LISTA_BLANCA_NEGRA,
        R.REG_ELIMINA_ENVIADOS,
        R.REG_ESTADO,
        CASE R.REG_ESTADO
            WHEN 0 THEN 'Vigente'
            WHEN 1 THEN 'Anulado'
            ELSE 'Desconocido'
        END AS REG_ESTADO_NOMBRE,
        R.EMP_RUT,
        R.REG_UPDATED_AT
    FROM tbl_regla R
    WHERE R.EMP_RUT = P_EMP_RUT
      AND (P_REG_ESTADO IS NULL OR R.REG_ESTADO = P_REG_ESTADO)
      AND (P_BUSCADOR = '' OR R.REG_NOMBRE LIKE CONCAT('%', P_BUSCADOR, '%'))
    ORDER BY
        CASE WHEN P_CAMPO = 1 AND P_ORDEN = 1 THEN R.REG_ID END ASC,
        CASE WHEN P_CAMPO = 1 AND P_ORDEN = 2 THEN R.REG_ID END DESC,
        CASE WHEN P_CAMPO = 2 AND P_ORDEN = 1 THEN R.REG_NOMBRE END ASC,
        CASE WHEN P_CAMPO = 2 AND P_ORDEN = 2 THEN R.REG_NOMBRE END DESC,
        CASE WHEN P_CAMPO = 3 AND P_ORDEN = 1 THEN R.REG_ELIMINA_ENVIADOS END ASC,
        CASE WHEN P_CAMPO = 3 AND P_ORDEN = 2 THEN R.REG_ELIMINA_ENVIADOS END DESC,
        CASE WHEN P_CAMPO = 4 AND P_ORDEN = 1 THEN R.REG_ESTADO END ASC,
        CASE WHEN P_CAMPO = 4 AND P_ORDEN = 2 THEN R.REG_ESTADO END DESC,
        R.REG_ID ASC;
END$$


