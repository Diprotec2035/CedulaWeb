DROP PROCEDURE IF EXISTS `SP_SEL_REPORTE_REGISTRO_VISITA`$$
CREATE DEFINER = 'UsuarioOwner'@'%' PROCEDURE `SP_SEL_REPORTE_REGISTRO_VISITA`(
        IN `P_EMP_RUT` VARCHAR(10),
        IN `P_BUSCADOR` VARCHAR(100),
        IN `P_OPERACION` TINYINT UNSIGNED,
        IN `P_DESDE` VARCHAR(10),
        IN `P_HASTA` VARCHAR(10),
        IN `P_CAMPO` TINYINT,
        IN `P_ORDEN` TINYINT
    )
    NOT DETERMINISTIC
    CONTAINS SQL
    SQL SECURITY DEFINER
    COMMENT ''
BEGIN
    SELECT RV.RV_RUT, RV.RV_NOMBRE_APELLIDO, RV.RV_EMPRESA,
           RV.RV_PATENTE, RV.RV_COMENTARIO, RV.RV_FOTOGRAFIA,
           RV.RV_ENTRADA_SALIDA,
           DATE_FORMAT(RV.RV_FECHA, '%d-%m-%Y') AS RV_FECHA,
           DATE_FORMAT(RV.RV_HORA, '%H:%i:%s') AS RV_HORA,
           RV.DIS_ID, DIS.DIS_MARCA, DIS.DIS_MODELO, DIS.DIS_SERIALNUMBER
    FROM tbl_registro_visita RV
    INNER JOIN tbl_dispositivo DIS ON DIS.DIS_ID = RV.DIS_ID
    WHERE RV.EMP_RUT = UPPER(TRIM(P_EMP_RUT))
      AND RV.RV_FECHA >= STR_TO_DATE(P_DESDE, '%d-%m-%Y')
      AND RV.RV_FECHA <= STR_TO_DATE(P_HASTA, '%d-%m-%Y')
      AND (P_OPERACION IS NULL OR RV.RV_ENTRADA_SALIDA = P_OPERACION)
      AND (P_BUSCADOR = ''
           OR RV.RV_RUT LIKE CONCAT('%', P_BUSCADOR, '%')
           OR RV.RV_NOMBRE_APELLIDO LIKE CONCAT('%', P_BUSCADOR, '%')
           OR RV.RV_EMPRESA LIKE CONCAT('%', P_BUSCADOR, '%'))
    ORDER BY
      CASE WHEN P_CAMPO = 1 AND P_ORDEN = 1 THEN RV.RV_RUT END ASC,
      CASE WHEN P_CAMPO = 1 AND P_ORDEN = 2 THEN RV.RV_RUT END DESC,
      CASE WHEN P_CAMPO = 2 AND P_ORDEN = 1 THEN RV.RV_NOMBRE_APELLIDO END ASC,
      CASE WHEN P_CAMPO = 2 AND P_ORDEN = 2 THEN RV.RV_NOMBRE_APELLIDO END DESC,
      CASE WHEN P_CAMPO = 3 AND P_ORDEN = 1 THEN RV.RV_EMPRESA END ASC,
      CASE WHEN P_CAMPO = 3 AND P_ORDEN = 2 THEN RV.RV_EMPRESA END DESC,
      CASE WHEN P_CAMPO = 4 AND P_ORDEN = 1 THEN RV.RV_FECHA END ASC,
      CASE WHEN P_CAMPO = 4 AND P_ORDEN = 2 THEN RV.RV_FECHA END DESC,
      RV.RV_HORA DESC, RV.RV_ID DESC;
END$$

