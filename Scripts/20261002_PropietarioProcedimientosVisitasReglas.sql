    COMMENT ''
BEGIN
    DECLARE V_EMP_RUT VARCHAR(10);
    DECLARE V_EV_RUT VARCHAR(10);
    DECLARE V_EV_NOMBRE VARCHAR(150);
    DECLARE V_EV_EMPRESA VARCHAR(50);
    DECLARE V_USU_RUT VARCHAR(10);
