CREATE DEFINER = 'UsuarioOwner'@'%' PROCEDURE `SP_UPD_EMPRESA_VISITA_V2`(
        IN `P_EMP_RUT` VARCHAR(10),
        IN `P_EV_RUT` VARCHAR(10),
        IN `P_EV_NOMBRE` VARCHAR(150),
        IN `P_EV_EMPRESA` VARCHAR(50),
        IN `P_EV_VIGENTE` TINYINT UNSIGNED,
        IN `P_EV_UPDATED_AT_ORIGINAL` DATETIME(6),
        IN `P_USU_RUT` VARCHAR(10),
        OUT `P_RETORNO` TINYINT UNSIGNED
    )
    NOT DETERMINISTIC
    CONTAINS SQL
    SQL SECURITY DEFINER
    COMMENT ''
BEGIN
    DECLARE V_EMP_RUT VARCHAR(10);
    DECLARE V_EV_RUT VARCHAR(10);
    DECLARE V_EV_NOMBRE VARCHAR(150);
    DECLARE V_EV_EMPRESA VARCHAR(50);
    DECLARE V_USU_RUT VARCHAR(10);
    DECLARE V_NOMBRE_ANTERIOR VARCHAR(150);
    DECLARE V_EMPRESA_ANTERIOR VARCHAR(50);
    DECLARE V_VIGENTE_ANTERIOR TINYINT UNSIGNED;
    DECLARE V_UPDATED_AT_ACTUAL DATETIME(6);
    DECLARE V_REGISTRO_EXISTE TINYINT UNSIGNED DEFAULT 1;
    DECLARE V_DETALLE TEXT DEFAULT '';
    DECLARE CONTINUE HANDLER FOR NOT FOUND
        SET V_REGISTRO_EXISTE = 0;
    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        ROLLBACK;
        SET P_RETORNO = 255;
    END;
    SET V_EMP_RUT = UPPER(TRIM(COALESCE(P_EMP_RUT, '')));
    SET V_EV_RUT = UPPER(TRIM(COALESCE(P_EV_RUT, '')));
    SET V_EV_NOMBRE = UPPER(TRIM(COALESCE(P_EV_NOMBRE, '')));
    SET V_EV_EMPRESA = UPPER(TRIM(P_EV_EMPRESA));
    SET V_USU_RUT = UPPER(TRIM(COALESCE(P_USU_RUT, '')));
    IF V_EMP_RUT = '' OR V_EV_RUT = '' OR V_EV_NOMBRE = ''
       OR V_USU_RUT = '' OR P_EV_VIGENTE IS NULL
       OR P_EV_VIGENTE NOT IN (0, 1)
       OR P_EV_UPDATED_AT_ORIGINAL IS NULL THEN
        SET P_RETORNO = 2;
    ELSE
        START TRANSACTION;
        SELECT EV_NOMBRE, EV_EMPRESA, EV_VIGENTE, EV_UPDATED_AT
        INTO V_NOMBRE_ANTERIOR, V_EMPRESA_ANTERIOR,
             V_VIGENTE_ANTERIOR, V_UPDATED_AT_ACTUAL
        FROM tbl_empresa_visita
        WHERE EMP_RUT = V_EMP_RUT
          AND EV_RUT = V_EV_RUT
        FOR UPDATE;
        IF V_REGISTRO_EXISTE = 0 THEN
            SET P_RETORNO = 1;
        ELSEIF NOT (V_UPDATED_AT_ACTUAL <=> P_EV_UPDATED_AT_ORIGINAL) THEN
            SET P_RETORNO = 3;
        ELSE
            IF NOT (V_NOMBRE_ANTERIOR <=> V_EV_NOMBRE) THEN
                SET V_DETALLE = CONCAT(
                    V_DETALLE, 'Nombre: "',
                    COALESCE(V_NOMBRE_ANTERIOR, ''),
                    '" -> "', V_EV_NOMBRE, '"; '
                );
            END IF;
            IF NOT (V_EMPRESA_ANTERIOR <=> V_EV_EMPRESA) THEN
                SET V_DETALLE = CONCAT(
                    V_DETALLE, 'Empresa: "',
                    COALESCE(V_EMPRESA_ANTERIOR, ''),
                    '" -> "', COALESCE(V_EV_EMPRESA, ''), '"; '
                );
            END IF;
            IF NOT (V_VIGENTE_ANTERIOR <=> P_EV_VIGENTE) THEN
                SET V_DETALLE = CONCAT(
                    V_DETALLE, 'Estado: "',
                    IF(V_VIGENTE_ANTERIOR = 0, 'Vigente', 'Anulado'),
                    '" -> "',
                    IF(P_EV_VIGENTE = 0, 'Vigente', 'Anulado'),
                    '"; '
                );
            END IF;
            IF V_DETALLE <> '' THEN
                UPDATE tbl_empresa_visita
                SET EV_NOMBRE = V_EV_NOMBRE,
                    EV_EMPRESA = V_EV_EMPRESA,
                    EV_VIGENTE = P_EV_VIGENTE,
                    EV_FECHA = CURRENT_DATE,
                    EV_HORA = CURRENT_TIME,
                    EV_UPDATED_AT = CURRENT_TIMESTAMP(6)
                WHERE EMP_RUT = V_EMP_RUT
                  AND EV_RUT = V_EV_RUT;
                CALL SP_INS_EMPRESA_VISITA_BITACORA(
                    V_EMP_RUT, V_EV_RUT, V_USU_RUT,
                    'MODIFICAR', 'Visita modificada', V_DETALLE
                );
            END IF;
            SET P_RETORNO = 0;
        END IF;
        COMMIT;
    END IF;
END$$

