DROP PROCEDURE IF EXISTS `SP_SEL_EMPRESA_VISITA_BITACORA`$$
CREATE DEFINER = 'UsuarioOwner'@'%' PROCEDURE `SP_SEL_EMPRESA_VISITA_BITACORA`(
        IN `P_EMP_RUT` VARCHAR(10),
        IN `P_EV_RUT` VARCHAR(10)
    )
    NOT DETERMINISTIC
    CONTAINS SQL
    SQL SECURITY DEFINER
    COMMENT ''
BEGIN
    SELECT
        EVB.EVB_ID AS BIT_ID,
        DATE_FORMAT(EVB.EVB_FECHA, '%d-%m-%Y') AS BIT_FECHA,
        DATE_FORMAT(EVB.EVB_HORA, '%H:%i:%s') AS BIT_HORA,
        EVB.USU_RUT,
        CONCAT(IFNULL(USU.USU_NOMBRE, ''), ' ',
               IFNULL(USU.USU_APELLIDO, '')) AS USU_NOMBRE,
        EVB.EVB_ACCION AS BIT_ACCION,
        EVB.EVB_COMENTARIOS AS BIT_COMENTARIOS,
        EVB.EVB_DETALLE AS BIT_DETALLE,
        EVB.EV_RUT AS BIT_REGISTRO_ID
    FROM tbl_empresa_visita_bitacora EVB
    LEFT JOIN tbl_usuario USU
        ON USU.USU_RUT = EVB.USU_RUT
    WHERE EVB.EMP_RUT = UPPER(TRIM(P_EMP_RUT))
      AND EVB.EV_RUT = UPPER(TRIM(P_EV_RUT))
    ORDER BY EVB.EVB_FECHA DESC, EVB.EVB_HORA DESC, EVB.EVB_ID DESC;
END$$

